//! Tiny 5x7 bitmap font used by the in-game help/status panel.

use sdl2::pixels::Color;
use sdl2::rect::Rect;
use sdl2::render::Canvas;
use sdl2::video::Window;

const GLYPH_W: i32 = 5;
const GLYPH_H: i32 = 7;

pub fn draw_text(
    canvas: &mut Canvas<Window>,
    text: &str,
    x: i32,
    y: i32,
    scale: i32,
    color: Color,
) -> Result<(), String> {
    let mut cursor = x;
    canvas.set_draw_color(color);
    for ch in text.chars() {
        if ch == ' ' {
            cursor += 4 * scale;
            continue;
        }
        let rows = glyph(ch.to_ascii_uppercase());
        for (row, bits) in rows.iter().copied().enumerate() {
            for col in 0..GLYPH_W {
                let mask = 1u8 << ((GLYPH_W - 1 - col) as u32);
                if bits & mask != 0 {
                    canvas.fill_rect(Rect::new(
                        cursor + col * scale,
                        y + row as i32 * scale,
                        scale as u32,
                        scale as u32,
                    ))?;
                }
            }
        }
        cursor += 6 * scale;
    }
    Ok(())
}

